export const GLYPH_W = 5;
/** Rows a glyph can use: seven plus the spacing row for descenders. */
export const GLYPH_H = 8;
/** Rows of the text body: the comb that finds lines looks for these. */
export const TEXT_H = 7;
/** Character cell advance, in dots. */
export const CELL_W = 6;
export const CELL_H = 8;

/** A glyph as a 5×8 array of 0/1 in row-major order. */
export function glyphBits(ch: string): Uint8Array {
  const cols = FONT_COLS[ch];
  if (!cols) throw new Error(`No glyph for ${JSON.stringify(ch)}`);
  const bits = new Uint8Array(GLYPH_W * GLYPH_H);
  for (let y = 0; y < GLYPH_H; y++) for (let x = 0; x < GLYPH_W; x++) bits[y * GLYPH_W + x] = (cols[x] >> y) & 1;
  return bits;
}
